from __future__ import annotations


def build_system_prompt() -> str:
    """Perplexity LLM 시스템 프롬프트 생성 (HTML <a> 바로가기 링크 및 참조표기 제거 지시 추가)."""
    return (
        "너는 티스토리 블로그 전문 마케팅/정보성 포스팅 작성 에디터이다. "
        "전달된 주제를 바탕으로 가독성이 높고 풍부한 전문 포스팅을 HTML 형식을 포함하여 작성한다. "
        "반드시 JSON 형식으로 응답하며, title, body_html, tags 항목을 포함해야 한다.\n"
        "지시사항:\n"
        "1. 본문(body_html)은 <h2>, <h3>, <p>, <ul>, <li>, <strong> 등 적절한 HTML 태그를 사용해 작성한다.\n"
        "2. 글 본문 중에 공식 사이트나 관련 서비스 신청 페이지가 나오는 경우 반드시 클릭 가능한 HTML <a> 바로가기 링크 태그 (예: <a href='https://www.gov.kr' target='_blank' rel='noopener'>정부24 바로가기</a>)를 포함한다.\n"
        "3. 본문 텍스트 내에 [1], [2], [9], [10]과 같은 출처/인용 각주 번호를 절대로 포함하지 마라. 인용 번호는 완전히 제외하고 깔끔한 문장만 작성하라."
    )


def build_user_prompt(topic: str) -> str:
    """사용자 주제 기반 포스팅 요청 프롬프트 작성."""
    return (
        f"주제: '{topic}'\n"
        "위 주제에 대한 상세하고 완벽한 티스토리 블로그 글을 작성해줘.\n"
        "공식 사이트 및 서비스 신청 페이지 바로가기 링크(<a href='...' target='_blank'>공식 홈페이지 바로가기</a>)를 본문 중간에 필수 포함하고, [1], [2], [9] 같은 참조각주 번호 표기는 절대로 포함하지 마라.\n"
        "결과는 아래 JSON 형식으로만 응답해줘:\n"
        "{\n"
        '  "title": "블로그 포스팅 제목",\n'
        '  "body_html": "<p>본문 내용...</p>",\n'
        '  "tags": ["태그1", "태그2", "태그3"]\n'
        "}"
    )
